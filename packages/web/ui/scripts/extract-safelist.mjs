// Enumerates every class any `variants()` call in this package can produce and
// writes them into a stylesheet Tailwind reads as a safelist.
//
// Why a running Vite server rather than an esbuild bundle: `src/index.ts` uses
// `import.meta.glob` (the gallery demo maps), which esbuild does not understand.
// `ssrLoadModule` transforms TSX, expands globs, and stubs CSS imports, so the
// modules load without a browser and without a build output on disk.
//
// Nothing is rendered. `variants()` runs at module scope, so importing the
// barrel is enough to populate the registry.
import { writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import react from '@vitejs/plugin-react';
import { createServer } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'styles/generated/safelist.css');

const HEADER = [
  '/* GENERATED by scripts/extract-safelist.mjs — do not edit.',
  '   Every class any variants() call in this package can produce, so Tailwind',
  '   emits utilities for classes that only ever exist as template literals',
  '   (`bg-${tone}-9`, `hover:bg-${tone}-10/40`) and are never scannable in source. */',
].join('\n');

async function collect() {
  const server = await createServer({
    root,
    configFile: false,
    logLevel: 'error',
    server: { middlewareMode: true, hmr: false, watch: null },
    plugins: [react()],
  });
  try {
    const mod = await server.ssrLoadModule('/src/index.ts');
    if (typeof mod.collectSafelist !== 'function') {
      throw new Error('`collectSafelist` is not exported from the package barrel');
    }
    return mod.collectSafelist();
  } finally {
    await server.close();
  }
}

function render(classes) {
  // Sorted so the git-diff gate in `tokens:verify` only fires on real changes,
  // never on module evaluation order. One directive per class rather than one
  // space-separated list: `@source` splits its argument on spaces only, so a
  // multi-line list would parse as a single unmatchable candidate — and a
  // one-line dump of several hundred classes is unreviewable in a diff.
  const sorted = [...new Set(classes)].sort();
  const body = sorted.map((c) => `@source inline("${c}");`).join('\n');
  return `${HEADER}\n${body}\n`;
}

const classes = await collect();
const next = render(classes);
const prev = (() => {
  try {
    return readFileSync(outFile, 'utf8');
  } catch {
    return null;
  }
})();

writeFileSync(outFile, next);
const verb = prev === null ? 'created' : prev === next ? 'unchanged' : 'updated';
console.log(`safelist ${verb}: ${new Set(classes).size} classes -> ${path.relative(root, outFile)}`);
